def sqlite_verify(e):
    db = sqlite3.connect(':memory:')
    try:
        for t in e['tables']:
            types=[]
            for i in range(len(t['columns'])):
                values=[r[i] for r in t['rows'] if r[i] is not None]
                numeric=bool(values) and all(re.fullmatch(r'-?\d+(\.\d+)?',str(x)) for x in values)
                types.append('NUMERIC' if numeric else 'TEXT')
            ident=lambda s:'"'+s.replace('"','""')+'"'
            cols=','.join(ident(c)+' '+typ for c,typ in zip(t['columns'],types))
            db.execute(f'CREATE TABLE {ident(t["title"])} ({cols})')
            db.executemany(f'INSERT INTO {ident(t["title"])} VALUES ({",".join("?" for _ in types)})', t['rows'])
        actual=db.execute(e['sql']).fetchall()
        expected=e['results'][0]['rows']
        def norm(x):
            if isinstance(x,float) and x.is_integer(): return str(int(x))
            return None if x is None else str(x)
        actual=[tuple(map(norm,r)) for r in actual]
        expected=[tuple(map(norm,r)) for r in expected]
        ordered='ORDER BY' in e['sql'].upper()
        good=actual==expected if ordered else collections.Counter(actual)==collections.Counter(expected)
        assert good,(e['id'],actual,expected)
        return dict(exampleId=e['id'],status='PASS',engine='SQLite',version=sqlite3.sqlite_version,rows=actual,ordered=ordered,
                    boundary='Original SQL with inferred NUMERIC/TEXT schema for displayed inputs; does not verify Oracle or unstated original DDL.')
    finally: db.close()

